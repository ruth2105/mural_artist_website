export const artworks = [...baseArtworks, ...additionalProjects]
  .map((artwork, index) => {
    const title = verifiedProjectTitles[artwork.id] || artwork.title;
    const selectedFile = featuredImageSelections[artwork.id];
    const selectedImage = selectedFile
      ? artwork.images.find((image) => image.src.endsWith(`/${encodeURIComponent(selectedFile)}`))
      : null;
    const firstImage = artwork.images[0];
    const firstVideoPoster = artwork.videos[0]?.poster;
    const isMajorProject = artwork.category === 'big-projects';
    const isCollaboration = artwork.category === 'collaborations';
    const imageFallback = firstImage?.src || firstVideoPoster;
    const thumbnailFallback = firstImage?.thumbnail || firstVideoPoster;

    return {
      ...artwork,
      title,
      images: artwork.images.map((image, imageIndex) => ({
        ...image,
        alt: `${title} - project image ${imageIndex + 1}`,
      })),
      displayOrder: majorProjectOrder[artwork.id] ?? artwork.displayOrder ?? index + 1,
      featured: isMajorProject || artwork.featured,
      featuredImage: selectedImage?.src || artwork.featuredImage || artwork.image || imageFallback,
      image: selectedImage?.src || artwork.image || imageFallback,
      thumbnail: selectedImage?.thumbnail || artwork.thumbnail || thumbnailFallback,
      contributionType: isCollaboration
        ? 'Collaborative project'
        : artwork.contributionType || (isMajorProject ? 'Individual project' : undefined),
    };
  })
  .sort((a, b) => (
    categoryOrder[a.category] - categoryOrder[b.category]
    || a.displayOrder - b.displayOrder
  ));

